/** Demo cards generated by the real engine from synthetic athletes. */
function demoCards() {
  const now = new Date();
  return (
    [
      ["dedicatedRunner", "PACER"],
      ["triathlete", "IRONMAN"],
      ["eliteMountainRunner", "SUMMIT"],
    ] as const
  ).map(([profile, name]) => ({
    ...buildCard(syntheticAthlete(PROFILES[profile], now), now),
    displayName: name,
    name,
    country: null,
  }));
}

