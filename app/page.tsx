import Link from "next/link";
import { Share2, ShieldCheck } from "lucide-react";
import { PlayerCard } from "@/components/PlayerCard";
import { TiltCard } from "@/components/TiltCard";
import { holoVars, TIER_THEMES } from "@/lib/card-theme";
import { buildCard } from "@/lib/engine";
import { PROFILES, syntheticAthlete } from "@/lib/fixtures";
import type { PlayerCard as PlayerCardData } from "@/types/player";

const ERRORS: Record<string, string> = {
  denied: "You declined the Strava connection. No data was stored.",
  scope: "We need permission to read your activities to build a card. Please allow activity access.",
  state: "Your sign-in session expired. Please try connecting again.",
  rate_limited: "Strava is rate limiting us right now. Please try again in a few minutes.",
  strava_auth: "Strava rejected the authorization. Please try connecting again.",
  strava_upstream: "Strava is having trouble responding. Please try again shortly.",
  config_error: "The server isn't configured for Strava yet (missing API credentials).",
};

/** Foil sheen for "holo rare" tiers only. */
const holoFor = (card: PlayerCardData) => (TIER_THEMES[card.tier].holoCard ? holoVars(card.tier) : undefined);

/** Demo cards generated by the real engine from synthetic athletes. */
function demoCards() {
  const now = new Date();
  return (
    [
      ["dedicatedRunner", "PACER"],
      ["triathlete", "IRONMAN"],
      ["eliteMountainRunner", "SUMMIT"],
    ] as const
  ).map(([profile, name]) => ({
    ...buildCard(syntheticAthlete(PROFILES[profile], now), now),
    displayName: name,
    name,
    country: null,
  }));
}

export default async function Home({ searchParams }: PageProps<"/">) {
  const { error, removed } = await searchParams;
  const errorMessage = typeof error === "string" ? (ERRORS[error] ?? "Something went wrong. Please try again.") : null;
  const [silver, gold, icon] = demoCards();

  return (
    <main className="mx-auto w-full max-w-6xl flex-1 px-4 py-10 sm:py-16">
      <nav className="mb-12 flex items-center justify-between">
        <span className="display text-xl tracking-tight">
          STRAVA<span className="text-strava">-FUT</span>
        </span>
        <Link href="/guide" className="font-accent text-xs uppercase tracking-wider text-muted hover:text-foreground">
          How it works
        </Link>
      </nav>

      <section className="grid grid-cols-1 items-center gap-12 lg:grid-cols-2">
        <div>
          <h1 className="display text-5xl leading-[0.9] tracking-tight sm:text-7xl">
            Your training
            <br />
            <span className="text-strava">rated 99</span>
          </h1>
          <p className="mt-5 max-w-md text-lg text-muted">
            Connect Strava and get an Ultimate Team–style player card built from a year of real runs, rides, swims and
            everything in between.
          </p>

          {errorMessage && (
            <p role="alert" className="mt-6 rounded-lg border border-red-500/30 bg-red-500/10 px-4 py-3 text-sm text-red-200">
              {errorMessage}
            </p>
          )}
          {removed && (
            <p role="status" className="mt-6 rounded-lg border border-line bg-surface px-4 py-3 text-sm text-muted">
              Your card was removed and Strava access revoked.
            </p>
          )}

          {/* Replace with Strava's official "Connect with Strava" button asset before launch (brand guidelines). */}
          {/* Full-page navigation on purpose: the route redirects off-site to Strava's OAuth screen. */}
          {/* eslint-disable-next-line @next/next/no-html-link-for-pages */}
          <a
            href="/api/auth/strava"
            className="mt-8 inline-flex items-center gap-3 rounded-lg bg-strava px-6 py-3.5 font-semibold text-white shadow-lg shadow-strava/20 transition hover:brightness-110"
          >
            Connect with Strava
          </a>
          <p className="mt-3 flex items-center gap-2 text-xs text-muted">
            <ShieldCheck className="h-4 w-4" aria-hidden /> Read-only access. Remove your card and revoke access any time.
          </p>
        </div>

        {/* Cards use container-query sizing, so they need explicit widths (no intrinsic size). */}
        <div className="mx-auto flex w-full max-w-[520px] items-center justify-center py-6">
          <TiltCard className="z-0 w-[34%] shrink-0 translate-y-4 -rotate-6 opacity-90 transition-opacity hover:z-20 hover:opacity-100" holo={holoFor(silver)}>
            <PlayerCard card={silver} className="w-full" />
          </TiltCard>
          <TiltCard className="z-10 -mx-[5%] w-[40%] shrink-0 hover:z-20" holo={holoFor(gold)}>
            <PlayerCard card={gold} className="w-full" />
          </TiltCard>
          <TiltCard className="z-0 w-[34%] shrink-0 translate-y-4 rotate-6 opacity-90 transition-opacity hover:z-20 hover:opacity-100" holo={holoFor(icon)}>
            <PlayerCard card={icon} className="w-full" />
          </TiltCard>
        </div>
      </section>

      <section className="grain mt-20 flex items-start gap-3 rounded-2xl border border-line p-5">
        <Share2 className="mt-0.5 h-5 w-5 shrink-0 text-strava" aria-hidden />
        <p className="text-sm text-muted">
          Every card gets a public page at <code className="text-foreground">/your-username</code> and an embeddable image at{" "}
          <code className="text-foreground">/your-username.png</code> for GitHub READMEs, Notion or Instagram stories.
        </p>
      </section>

      <footer className="mt-16 text-center text-xs text-muted">Powered by Strava · Not affiliated with EA Sports or Strava</footer>
    </main>
  );
}
