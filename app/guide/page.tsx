import { SectionHeading } from "@/components/SectionHeading";
import { TiltCard } from "@/components/TiltCard";
import { TrophyBadge } from "@/components/TrophyBadge";
import { holoVars, TIER_THEMES } from "@/lib/card-theme";
import { buildCard, LEGACY_GATE, OVR_WEIGHTS, TIER_THRESHOLDS } from "@/lib/engine";
import { RATING_BANDS, ratingWord, STAT_INPUTS, STAT_MEASURES } from "@/lib/explain";
import { PROFILES, syntheticAthlete } from "@/lib/fixtures";
import { formatValue, TROPHIES } from "@/lib/trophies";
import { ATTRIBUTE_KEYS, type AttributeKey, type CardTier } from "@/types/player";

export const metadata: Metadata = {
  title: "Guide",
  description: "How Strava-FUT rates athletes: tiers, stats and every trophy.",
};

const STAT_NAMES: Record<AttributeKey, string> = {
  PAC: "Pace",
  END: "Endurance",
  PWR: "Power",
  CONS: "Consistency",
  VAR: "Versatility",
  PHY: "Physicality",
};

/** One demo card per tier, generated by the real engine. */
function tierCards() {
  const now = new Date();
  const byTier: [CardTier, keyof typeof PROFILES][] = [
    ["bronze", "casualJogger"],
    ["silver", "dedicatedRunner"],
    ["gold", "triathlete"],
    ["icon", "eliteMountainRunner"],
  ];
  return byTier.map(([tier, profile]) => ({
    tier,
    card: { ...buildCard(syntheticAthlete(PROFILES[profile], now), now), displayName: TIER_THEMES[tier].terrain.toUpperCase(), name: TIER_THEMES[tier].terrain },
  }));
}

function tierRange(tier: CardTier) {
  const i = TIER_THRESHOLDS.findIndex((t) => t.tier === tier);
  const min = TIER_THRESHOLDS[i].min;
  const max = i === 0 ? 99 : TIER_THRESHOLDS[i - 1].min - 1;
  return `${min}–${max}`;
}

